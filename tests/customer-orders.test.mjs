await db.exec("set test.admin='true'");
await assert.rejects(update(null,'https://square.link/u/test',true),/QUOTE_REQUIRED/);
await assert.rejects(update(600,'https://example.test/pay',true),/INVALID_PAYMENT_LINK/);
await assert.rejects(update(600,'https://square.link/u/test',true,'未入金','発送済'),/PAYMENT_REQUIRED/);
