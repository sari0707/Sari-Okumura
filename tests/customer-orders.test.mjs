const retry=(await place([{productId,qty:2}])).rows[0].result;assert.deepEqual(retry,first);
await assert.rejects(place([{productId,qty:3}],9900),/REQUEST_CHANGED/);
await assert.rejects(place([{productId,qty:1}],1,randomUUID()),/PRICE_CHANGED/);
await assert.rejects(place([{productId,qty:0}],0,randomUUID()),/INVALID_ITEMS/);
await assert.rejects(place([{productId,qty:-1}],0,randomUUID()),/INVALID_ITEMS/);
